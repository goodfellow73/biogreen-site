#!/usr/bin/env python3
"""data/redirects-old-site.csv -> .htaccess (Apache / LiteSpeed, e.g. Hostinger).

Run from the site root:   python tools/build-redirects.py

The table is the client's (24/11/2026): one row per address of the old
WordPress/WooCommerce site, old_url,new_url,note. Besides those rows:

  * one address for the whole site: http and the bare domain go to
    https://www.bio-green.co.il/ (301);
  * any other old shop address (/shop/…, /product/…, /product-category/…)
    goes to /products/;
  * the spam "sitemaps" planted in the old robots.txt (/css/goods.php?…)
    answer 410 Gone — never a redirect, so search engines drop them;
  * the build's own folders (tools, data, .git, .github) are not served;
  * a missing page gets /404.html with a real 404 status.

Old addresses are matched decoded (the server compares the URL path after
%-decoding), with or without the trailing slash; the query string is dropped.
"""

import csv
import os
import re
import sys
from urllib.parse import unquote, urlparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'data', 'redirects-old-site.csv')
OUT = os.path.join(ROOT, '.htaccess')
HOST = 'www.bio-green.co.il'
CATCH_ALL = ('shop', 'product', 'product-category')


def rows():
    out, special = [], []
    with open(TABLE, encoding='utf-8-sig', newline='') as f:
        for r in csv.DictReader(f):
            old, new = (r.get('old_url') or '').strip(), (r.get('new_url') or '').strip()
            if not old.startswith('http'):
                special.append((old, new))          # the catch-all and 410 lines, built in below
                continue
            path = unquote(urlparse(old).path)
            if not new.startswith('/'):
                sys.exit(f'build-redirects: target must start with "/": {new!r}')
            target = os.path.join(ROOT, new.lstrip('/'), 'index.html') if new != '/' else os.path.join(ROOT, 'index.html')
            if not os.path.exists(target):
                sys.exit(f'build-redirects: {new} does not exist on the new site ({path})')
            out.append((path, new))
    seen = {}
    for path, new in out:
        key = path.rstrip('/')
        if key in seen and seen[key] != new:
            sys.exit(f'build-redirects: {path} listed twice with different targets')
        seen[key] = new
    return out, special


def pattern(path):
    p = path.strip('/')
    return '^' + re.escape(p).replace('\\-', '-').replace('\\ ', ' ') + '/?$'


def main():
    table, special = rows()
    lines = [
        '# Generated by tools/build-redirects.py from data/redirects-old-site.csv.',
        '# Edit the table, not this file.',
        '',
        'Options -Indexes',
        'DirectoryIndex index.html',
        'ErrorDocument 404 /404.html',
        'AddDefaultCharset utf-8',
        '',
        '<IfModule mod_rewrite.c>',
        'RewriteEngine On',
        '',
        '# One address: https and www (a proxy in front may terminate TLS and say so',
        '# in X-Forwarded-Proto).',
        'RewriteCond %{HTTP_HOST} ^bio-green\\.co\\.il$ [NC]',
        f'RewriteRule ^ https://{HOST}%{{REQUEST_URI}} [R=301,L,NE]',
        'RewriteCond %{HTTP_HOST} ^www\\.bio-green\\.co\\.il$ [NC]',
        'RewriteCond %{HTTPS} !=on',
        'RewriteCond %{HTTP:X-Forwarded-Proto} !=https',
        f'RewriteRule ^ https://{HOST}%{{REQUEST_URI}} [R=301,L,NE]',
        '',
        '# The build\'s own files are not part of the site.',
        'RewriteRule ^(?:\\.git|\\.github|tools|data)(?:/|$) - [R=404,L]',
        'RewriteRule ^(?:README\\.md|\\.gitignore|\\.nojekyll)$ - [R=404,L]',
        '',
        '# Spam "sitemaps" planted in the old site\'s robots.txt: gone for good.',
        'RewriteRule ^css/goods\\.php$ - [G,L]',
        '',
        f'# The old site, address by address ({len(table)}).',
    ]
    for path, new in table:
        lines.append(f'RewriteRule {pattern(path)} {new}? [R=301,L]')
    lines += [
        '',
        '# Every other old shop address.',
        f'RewriteRule ^(?:{"|".join(CATCH_ALL)})(?:/.*)?$ /products/? [R=301,L]',
        '</IfModule>',
        '',
        '# Pages are rebuilt often: browsers check back; CSS/JS/images carry ?v= stamps.',
        '<IfModule mod_headers.c>',
        '<FilesMatch "\\.html$">',
        'Header set Cache-Control "no-cache"',
        '</FilesMatch>',
        '</IfModule>',
        '',
    ]
    text = '\n'.join(lines)
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if old != text:
        open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'redirects: {len(table)} old address(es) + shop catch-all + 410 for /css/goods.php -> .htaccess'
          + ('' if old != text else ' (unchanged)'))


if __name__ == '__main__':
    main()
