"""Knowledge articles: a page per article, and the hub's cards and tabs.

Run from the site root, after tools/sync-shell.py:   python tools/build-articles.py

Articles and their categories are edited in WordPress (plugin 1.8.0, menu
"מאמרים") and pulled into data/articles.json by tools/pull-from-wp.py:

    topics    name, background colour (a key of COLORS), icon, order
    articles  title, slug, category, body (the block editor's HTML), the
              short answer, the summary, FAQ, the card's title and sentence,
              the closing call to action, SEO title and description, dates

Each article becomes knowledge/<slug>/index.html, marked as generated; a
marked page whose article is gone is deleted. knowledge/index.html gets one
card per article, in its category's colour, and one tab per category that has
articles, in the categories' order.

The body is the editor's HTML cut down to what an article uses — headings,
paragraphs, lists, quotes, bold, italic and links — so nothing pasted into
WordPress can bring its own styles or scripts onto the site. Links into the
site are rewritten relative to the page.
"""

