def prune(keep):
    """Delete generated article pages whose article is gone. A page without
    the marker is somebody's hand-written page and is left alone."""
    removed = []
    base = os.path.join(ROOT, 'knowledge')
    for name in sorted(os.listdir(base)):
        d = os.path.join(base, name)
        p = os.path.join(d, 'index.html')
        if name in keep or not os.path.isdir(d) or os.listdir(d) != ['index.html']:
            continue
        if MARKER not in open(p, encoding='utf-8').read():
            continue
        os.remove(p)
        os.rmdir(d)
        removed.append(f'knowledge/{name}/')
    return removed


# ------------------------------------------------------------------- hub

def card(art, topic):
    color = topic['color'] if topic['color'] in COLORS else 'sky'
    icon = topic['icon'] if topic['icon'] in ICONS else 'book-open'
    return f'''      <article class="k-card k-card--{color}" data-category="{a(topic['slug'])}">
        <span class="k-card__icon"><svg class="icon" width="22" height="22" aria-hidden="true"><use href="#i-{icon}"></use></svg></span>
        <p class="k-card__cat">{e(topic['name'])}</p>
        <h3 class="k-card__title"><a href="{a(art['slug'])}/">{e(art.get('card_title') or art['title'])}</a></h3>
        <p class="k-card__text">{e(art.get('card_text'))}</p>
        <span class="k-card__more" aria-hidden="true">קראו עוד<svg class="icon" width="18" height="18"><use href="#i-arrow-left"></use></svg></span>
      </article>
'''


def between(src, name, body):
    return re.sub(r'(<!-- %s:start -->\n).*?(<!-- %s:end -->)' % (name, name),
                  lambda m: m.group(1) + body + m.group(2), src, flags=re.S)


def main():
    if not os.path.exists(DATA):
        print('articles: no data/articles.json, nothing to do')
        return
    data = json.load(open(DATA, encoding='utf-8'))
    topics = {t['slug']: t for t in data.get('topics', [])}
    order = sorted(topics.values(), key=lambda t: (int(t.get('order') or 0), t['name']))
    pre, post = shell()

    written, placed = [], []
    for art in data.get('articles', []):
        slug = art.get('slug', '')
        if not re.fullmatch(r'[a-z0-9-]+', slug) or slug in ('glossary', 'guide-thanks'):
            sys.exit(f'build-articles: article {art.get("id")} has the slug {slug!r}, '
                     'which cannot be an address under /knowledge/')
        topic = topics.get(art.get('topic'))
        if not topic:
            print(f"  note: '{art['title']}' has no category; it is published but gets no card")
        path = os.path.join(ROOT, 'knowledge', slug, 'index.html')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        new = page(art, topic or {'slug': '', 'name': 'ידע מקצועי', 'color': 'sky', 'icon': 'book-open'}, pre, post)
        # Written unstamped; stamp-assets.py, last in the build, puts the ?v=
        # stamps back, so an unchanged article ends the build unchanged.
        open(path, 'w', encoding='utf-8', newline='\n').write(new)
        written.append(slug)
        if topic:
            placed.append((order.index(topic), art.get('published') or '', art, topic))

    removed = prune(set(written))

    # Cards: by category order, newest first within a category.
    placed.sort(key=lambda p: p[1], reverse=True)
    placed.sort(key=lambda p: p[0])
    cards = ''.join(card(art, topic) for _, _, art, topic in placed)
    used = {topic['slug'] for _, _, _, topic in placed}
    tabs = '        <button class="bg-tab bg-tab--active" type="button" role="tab" aria-selected="true" data-filter="all">הכל</button>\n'
    for t in order:
        if t['slug'] in used:
            tabs += (f'        <button class="bg-tab" type="button" role="tab" aria-selected="false" '
                     f'data-filter="{a(t["slug"])}">{e(t["name"])}</button>\n')
    before = open(HUB, encoding='utf-8').read()
    hub = between(between(before, 'knowledge:tabs', tabs), 'knowledge:cards', cards)
    if hub != before:
        open(HUB, 'w', encoding='utf-8', newline='\n').write(hub)

    print(f'articles: {len(written)} page(s), {len(placed)} card(s) in {len(used)} categor{"y" if len(used) == 1 else "ies"}'
          + ''.join(f'\n  removed (no longer in WordPress): {r}' for r in removed))


if __name__ == '__main__':
    main()
